"""B-118 N15, N21, N8: the assembly steps of the E50 results and of the Phase 6 confirmatory family
(tools/atc/e50_build.py, tools/atc/phase6_family.py). Tiny files in a temporary folder stand in for the cell caches
and for results/E56_integrity.json; no simulation is run.

Generated by /ship (test coverage audit, 14 Nov 2026).

Value: protects=keep_superseded keeps the pre-fix values under the dated key across rebuilds and lists the fleet
  multiples not rerun; fails_when=a rebuild overwrites the dated block with post-fix values, drops an older
  superseded_* key, or nests superseded keys inside the block; why_new=no test imports e50_build; seam=none;
  no_claim=the real results files' contents (a temporary file stands in for results/E50_summary.json)
Value: protects=e50_build.cells refuses cell caches made with different code versions; fails_when=the code check is
  removed or compares nothing, so stale and fresh cells are pooled into one table; why_new=test_e50_near_staged covers
  run_e50_near's own check only; seam=none; no_claim=that the fingerprint itself changes when the code does
Value: protects=phase6_family._e50 refuses a family whose E50 cells come from different code, across fleet multiples;
  fails_when=the check is per multiple only, or removed; why_new=no test imports phase6_family; seam=none;
  no_claim=the family's statistics (only the loading step is exercised)
Value: protects=H15a's p-value is (resamples at or above 0 + 1) / (resamples + 1) from the saved count, and the family
  stops without a count that reproduces the stored interval; fails_when=p falls back to 1 / (B + 1) whatever the
  count, or a missing or non-reproducing count is accepted; why_new=no test imports phase6_family; seam=none;
  no_claim=that the saved count is right (lunarsim.nn.evaluate --resample-counts makes it; a typed file stands in)
"""
import gzip
import json
import os
import pickle
import sys

import pytest

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
sys.path.insert(0, os.path.join(ROOT, "tools", "atc"))


def _cell(folder, mult, seed, code):
    os.makedirs(folder, exist_ok=True)
    with gzip.open(os.path.join(folder, f"m{mult}_s{seed}.pkl.gz"), "wb") as f:
        pickle.dump({"mult": mult, "seed": seed, "code": code}, f)


def _write(path, doc):
    with open(path, "w", encoding="utf-8") as f:
        json.dump(doc, f)


def test_keep_superseded_keeps_the_pre_fix_values_across_rebuilds(tmp_path):
    import e50_build as EB
    path = str(tmp_path / "summary.json")
    # no previous file: nothing to carry, only the multiples not rerun
    first = EB.keep_superseded(path, {"p95": 1.0}, [1, 4, 8], ["1", 4])
    assert first == {"p95": 1.0, "multiples_not_rerun_yet": [8]}
    # a previous file made before the fix, which itself carries an older superseded block
    _write(path, {"p95": 5.0, "seeds": 30, "superseded_2026-01-01_older": {"p95": 9.0}})
    doc = EB.keep_superseded(path, {"p95": 6.0}, [1, 4, 8], [1, 4, 8])
    block = doc[EB.SUPERSEDED_BLOCK]
    assert doc["p95"] == 6.0 and doc["multiples_not_rerun_yet"] == []
    assert block["p95"] == 5.0 and block["seeds"] == 30 and block["superseded_on"] == "2026-11-13" and block["reason"]
    assert doc["superseded_2026-01-01_older"] == {"p95": 9.0}
    assert not any(k.startswith("superseded_") and k != "superseded_on" for k in block)   # no block inside the block
    # a later rebuild (the file now holds post-fix values and the block): the pre-fix values stay as they were
    _write(path, doc)
    again = EB.keep_superseded(path, {"p95": 7.0})
    assert again["p95"] == 7.0 and again[EB.SUPERSEDED_BLOCK] == block
    assert again["superseded_2026-01-01_older"] == {"p95": 9.0} and "multiples_not_rerun_yet" not in again


def test_e50_cells_refuse_mixed_code(monkeypatch, tmp_path):
    import e50_build as EB
    cache = str(tmp_path / "e50")
    monkeypatch.setattr(EB, "CACHE", cache)
    _cell(cache, 1, 1, "aaa")
    _cell(cache, 1, 2, "aaa")
    _cell(cache, 4, 1, "aaa")
    got = EB.cells()
    assert sorted(got) == [(1, 1), (1, 2), (4, 1)] and got[(4, 1)]["code"] == "aaa"
    _cell(cache, 8, 1, "bbb")                              # one cell made with other code
    with pytest.raises(SystemExit, match="different code"):
        EB.cells()


def test_family_refuses_e50_cells_of_mixed_code_across_multiples(monkeypatch, tmp_path):
    import phase6_family as PF
    monkeypatch.setattr(PF, "ROOT", str(tmp_path))
    monkeypatch.setattr(PF, "E50_CODES", set())
    cache = str(tmp_path / ".cache" / "atc" / "e50")
    _cell(cache, 1, 1, "aaa")
    _cell(cache, 1, 2, "aaa")
    _cell(cache, 4, 1, "bbb")                              # each multiple is uniform; the family is not
    assert sorted(PF._e50(1)) == [1, 2] and PF.E50_CODES == {"aaa"}
    with pytest.raises(SystemExit, match="different code"):
        PF._e50(4)


def test_h15a_p_comes_from_the_saved_resample_count(monkeypatch, tmp_path):
    import phase6_family as PF
    monkeypatch.setattr(PF, "ROOT", str(tmp_path))
    os.makedirs(tmp_path / "results")
    path = str(tmp_path / "results" / "E56_integrity.json")
    key = "chi2_step|drift|delay_median_diff_s"
    stat = {"value": -12.5, "ci95": [-20.0, -4.0], "ci90": [-18.0, -6.0]}
    doc = {"test": {"h15_net_against": {"chi2_step": {"drift": {"delay_median_diff_s": stat}}}},
           "h15_resample_counts_b118": {"sets": {"test": {key: {"reproduces_stored_interval": True, "boot_n": 1000,
                                                                "at_or_above_0": 3}}}}}
    _write(path, doc)
    h = PF.h15a()
    assert h["p"] == pytest.approx(4.0 / 1001.0) and h["resamples_at_or_above_0"] == 3 and h["resamples"] == 1000
    assert h["delay_median_diff_s"] == -12.5 and h["ci95"] == [-20.0, -4.0]
    doc["h15_resample_counts_b118"]["sets"]["test"][key]["at_or_above_0"] = 0
    _write(path, doc)
    assert PF.h15a()["p"] == pytest.approx(1.0 / 1001.0)        # no resample at or above 0: the bound, as before
    doc["h15_resample_counts_b118"]["sets"]["test"][key]["reproduces_stored_interval"] = False
    _write(path, doc)
    with pytest.raises(SystemExit, match="resample-counts"):   # a count that does not give the stored interval back
        PF.h15a()
    del doc["h15_resample_counts_b118"]
    _write(path, doc)
    with pytest.raises(SystemExit, match="resample-counts"):   # no saved count
        PF.h15a()
